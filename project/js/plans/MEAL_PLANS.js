/**
 * احصل على خطة يوم معين
 * @param {number} kcal - مستوى السعرات (1200, 1400, 1600, 1800, 2000, 2200, 2500)
 * @param {number} dayIndex - رقم اليوم (0-29)
 */
function getPlanDay(kcal, dayIndex) {
  const plan = MEAL_PLANS[kcal];
  if (!plan) return null;
  return plan[dayIndex % 30] || null;
}

/**
 * احصل على أقرب مستوى سعرات متاح
 * @param {number} targetKcal - الهدف اليومي من calcDailyGoal()
 */
function getNearestPlanKcal(targetKcal) {
  const levels = [1200, 1400, 1600, 1800, 2000, 2200, 2500];
  return levels.reduce((prev, curr) =>
    Math.abs(curr - targetKcal) < Math.abs(prev - targetKcal) ? curr : prev
  );
}

/**
 * احصل على الماكرو المستهدف لمستوى معين
 * @param {number} kcal - مستوى السعرات
 */
function getMacroTargets(kcal) {
  const nearest = getNearestPlanKcal(kcal);
  return MACRO_TARGETS[nearest];
}

