/**
 * استبدل الأصناف المحظورة في نص الوجبة
 * @param {string} mealText - نص الوجبة
 * @param {object} replacements - قاموس الاستبدال
 * @param {string[]} forbidden - قائمة الكلمات المحظورة
 */
function _applyReplacements(mealText, replacements, forbidden) {
  if (!mealText) return mealText;

  let result = mealText;

  // 1. استبدال مباشر بالاسم الكامل
  for (const [original, replacement] of Object.entries(replacements)) {
    if (result.includes(original)) {
      result = result.replace(original, replacement);
    }
  }

  // 2. معالجة صيغة "X أو Y" — لو X محظور، خذ Y
  if (result.includes(' أو ')) {
    const parts = result.split(' أو ');
    const firstPart = parts[0].trim();
    const isForbidden = forbidden.some(f => firstPart.includes(f));
    if (isForbidden && parts.length > 1) {
      result = parts[1].trim();
    }
  }

  return result;
}

/**
 * طبّق نظام غذائي على يوم كامل
 * @param {object} dayPlan - يوم من MEAL_PLANS (wakeup, breakfast, ...)
 * @param {string|string[]} profiles - اسم النظام أو مصفوفة أنظمة
 * @returns {object} - يوم معدّل
 */
function applyDietProfile(dayPlan, profiles) {
  if (!dayPlan) return null;

  // تحويل string لـ array
  const profileList = Array.isArray(profiles) ? profiles : [profiles];

  // دمج قواميس الاستبدال والمحظورات
  const combinedReplacements = {};
  const combinedForbidden = [];

  for (const profile of profileList) {
    if (DIET_REPLACEMENTS[profile]) {
      Object.assign(combinedReplacements, DIET_REPLACEMENTS[profile]);
    }
    if (DIET_FORBIDDEN[profile]) {
      combinedForbidden.push(...DIET_FORBIDDEN[profile]);
    }
  }

  // تطبيق على كل وجبة
  const mealKeys = ['wakeup','breakfast','coffee','snack1','prelunch','lunch','snack2','dinner','bedtime'];
  const result = { ...dayPlan };

  for (const key of mealKeys) {
    if (result[key]) {
      result[key] = _applyReplacements(result[key], combinedReplacements, combinedForbidden);
    }
  }

  result._dietProfile = profileList;
  return result;
}

/**
 * طبّق نظام غذائي على خطة كاملة (30 يوم)
 * @param {object[]} plan - مصفوفة الأيام
 * @param {string|string[]} profiles
 */
function applyDietProfileToFullPlan(plan, profiles) {
  return plan.map(day => applyDietProfile(day, profiles));
}

/**
 * احصل على اسم النظام بالعربي
 */
const DIET_PROFILE_NAMES = {
  pescatarian: 'بيسكاتاريان (سمك فقط)',
  vegan:       'نباتي صرف',
  glutenFree:  'خالي من الجلوتين',
  lactoseFree: 'خالي من اللاكتوز',
  nutFree:     'خالي من المكسرات',
};

/**
 * فحص هل يوم معين مناسب لنظام معين (بعد التطبيق)
 * @param {object} dayPlan - اليوم
 * @param {string} profile - النظام
 */
function checkDietCompliance(dayPlan, profile) {
  const forbidden = DIET_FORBIDDEN[profile] || [];
  const mealKeys = ['wakeup','breakfast','coffee','snack1','prelunch','lunch','snack2','dinner','bedtime'];
  const violations = [];

  for (const key of mealKeys) {
    const meal = dayPlan[key] || '';
    for (const f of forbidden) {
      if (meal.includes(f)) {
        violations.push({ meal: key, text: meal, forbidden: f });
      }
    }
  }

  return { compliant: violations.length === 0, violations };
}

